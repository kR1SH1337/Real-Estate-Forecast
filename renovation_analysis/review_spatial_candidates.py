records, pair_records, matched_unique = [], [], {}
for sid, ps in groups.items():
    site = sites[sid]
    addr = site['address']
    ids = accepted.get(addr, [])
    if ids:
        status = 'MATCH_STRONG'
        selected = [p for p in ps if int(p['eis_id']) in ids]
        assert len(selected) == len(ids)
        n = sum(int(p['eis_apartments']) for p in selected)
        assert n == int(site['apartments']), (addr, n, site['apartments'])
        reason = ('Одна площадка соответствует трём корпусам по одному РНС 77-03-022351-2025: 537 + 170 + 170 = 877 квартир. Соседний ID 66957 относится к з/у 14.'
                  if len(ids) > 1 else aliases.get(addr, 'Совпадают адрес/номер участка и квартирность; координаты согласуются.'))
        for p in selected:
            assert p['eis_id'] not in matched_unique
            matched_unique[p['eis_id']] = p
    elif addr in conflicts:
        status, reason = 'CONFLICT', conflicts[addr]
    else:
        assert addr in negative_notes, addr
        status, reason = 'NOT_MATCHED', negative_notes[addr]
    records.append(dict(site_id=sid, address=addr, fund_apartments=int(site['apartments']),
        status=status, accepted_eis_ids=ids, candidate_eis_ids=[int(p['eis_id']) for p in ps],
        reason=reason, fund_url=site['fund_source_url'], additional_sources=sources_extra.get(addr, [])))
    for p in ps:
        own = int(p['eis_id']) in ids
        pair_reason = reason if own or not ids else 'Соседний корпус; для этой площадки установлены другие ID: ' + ', '.join(map(str, ids)) + '.'
        pair_records.append(dict(p, review_status='MATCH_STRONG' if own else ('CONFLICT' if status == 'CONFLICT' else 'NOT_ACCEPTED'),
            review_reason=pair_reason, eis_url='https://наш.дом.рф/сервисы/каталог-новостроек/объект/' + p['eis_id']))

counts = Counter(r['status'] for r in records)
stats = dict(sites_in_inventory=len(sites), sites_with_candidates=len(records), candidate_pairs=len(pairs),
    sites_by_status=dict(counts), strongly_matched_unique_eis_buildings=len(matched_unique),
    strongly_matched_apartments=sum(int(p['eis_apartments']) for p in matched_unique.values()),
    strongly_matched_apartment_area_m2=round(sum(float(p['apartment_area_m2']) for p in matched_unique.values()), 2),
    matched_fund_developer_buildings=sum('ФОНД' in p['developer'] for p in matched_unique.values()),
    matched_escrow_buildings=sum(p['financing_field'] == 'Эскроу' for p in matched_unique.values()),
    outside_200m_not_reviewed=len(sites)-len(records))
assert len(records) == 41 and len(pair_records) == 69
